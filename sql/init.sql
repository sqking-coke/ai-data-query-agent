-- ============================================
-- 业务数据智能查询Agent - 完整数据库初始化脚本
-- 适用: MySQL 8.0+
-- ============================================
CREATE DATABASE IF NOT EXISTS `ai-data-query-agent`
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_general_ci;

USE `ai-data-query-agent`;

-- =====================================================
-- 订单信息表（AI数据查询Agent的示例数据源）
-- =====================================================
DROP TABLE IF EXISTS `order_info`;

CREATE TABLE `order_info` (
                              id           BIGINT         NOT NULL AUTO_INCREMENT  COMMENT '主键ID',
                              order_no     VARCHAR(32)    NOT NULL                 COMMENT '订单编号',
                              order_amount DECIMAL(12,2)  NOT NULL DEFAULT 0.00    COMMENT '订单金额',
                              order_status TINYINT        NOT NULL DEFAULT 1       COMMENT '订单状态：0=异常, 1=正常',
                              create_time  DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
                              PRIMARY KEY (id),
                              UNIQUE KEY uk_order_no (order_no),
                              KEY idx_create_time (create_time),
                              KEY idx_order_status (order_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单信息表';

